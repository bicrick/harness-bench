"""Write the harness-bench post's grid data (personal-website src/components/project/harness/grid.js).

Same-settings rows (thinking off) from results/swebench/summary_tokens.csv; Cursor and Claude Code use the
full-log reruns (cursor_nothink2, claude_code_nothink2). psf__requests-2317 excluded (replaced by psf__requests-1142).
Finish order: each run's finish time (stdout.txt mtime for the reruns, run folder mtime otherwise), measured from
each harness's own first run so all five start together.
Usage: python3 scripts/post_grid.py [path/to/grid.js]"""
import csv, json, os, sys
H = [('swe_agent', 'swe_agent_nothink'), ('cursor', 'cursor_nothink2'), ('opencode', 'opencode_nothink'),
     ('mini', 'mini_swe_agent_nothink'), ('claude_code', 'claude_code_nothink2')]
OUT = sys.argv[1] if len(sys.argv) > 1 else '/workspace/personal-website/src/components/project/harness/grid.js'
src = {b: a for a, b in H}; full = dict(H)
rows = {}
for r in csv.DictReader(open('results/swebench/summary_tokens.csv')):
    if r['harness'] in src and r['instance_id'] != 'psf__requests-2317':
        rows[(r['instance_id'], src[r['harness']])] = r
tasks = sorted({k[0] for k in rows}); assert len(tasks) == 50, len(tasks)
def finished(t, h):
    p = f'results/swebench/runs/{t}/{full[h]}'
    f = p + '/stdout.txt' if full[h].endswith('2') else p
    return os.path.getmtime(f) if os.path.exists(f) else 0
ev = []
for (t, h), r in rows.items():
    usd = float(r['usd']) or float(r['usd_est'] or 0)
    ev.append([finished(t, h), t, h, r['resolved'] == 'True', usd, float(r['wall_s'])])
st = {}
for e in ev: st[e[2]] = min(st.get(e[2], 1e18), e[0])
for e in ev: e[0] -= st[e[2]]
ev.sort()
ids = [a for a, b in H]
solved = {t: sum(1 for e in ev if e[1] == t and e[3]) for t in tasks}
tasks.sort(key=lambda t: (-solved[t], t))
cells = [[None] * 5 for _ in tasks]; order = []
for m, t, h, ok, usd, w in ev:
    r = tasks.index(t); c = ids.index(h); order.append([r, c])
    cells[r][c] = [1 if ok else 0, round(usd * 1e5) / 1e5, round(w)]
none = sum(1 for t in tasks if solved[t] == 0); allx = sum(1 for t in tasks if solved[t] == 5)
out = f"""// Five harnesses (Aider left out). Generated by bicrick/harness-bench scripts/post_grid.py from
// results/swebench/summary_tokens.csv (same-settings *_nothink rows; Cursor and Claude Code from the full-log
// reruns cursor_nothink2 / claude_code_nothink2; psf__requests-2317 excluded).
// GRID_TASKS rows sorted by how many harnesses fixed them. GRID_CELLS[row][col] = [fixed, usd, wall_s].
// GRID_ORDER = [row, col] in the order the runs actually finished (measured from each harness's own first run so all five start together).
// Cursor usd is estimated from its own token logs.
export const GRID_COLS = {json.dumps(ids)};
export const GRID_TASKS = {json.dumps(tasks)};
export const GRID_CELLS = {json.dumps(cells)};
export const GRID_ORDER = {json.dumps(order)};
export const GRID_NONE = {none};
export const GRID_ALL = {allx};
"""
open(OUT, 'w').write(out)
print('none', none, 'all', allx, 'solved per column', [sum(cells[r][c][0] for r in range(50)) for c in range(5)])
